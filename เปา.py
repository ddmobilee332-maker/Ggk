def หน้าหลัก():
    แสดงโลโก้เปา()
    ลิงก์ = input("\x1b[36m[เปา] วางลิงก์คลิปวิดีโอที่นี่: \x1b[0m").strip()
    
    if not ลิงก์:
        print('\x1b[31m[!] กรุณาใส่ลิงก์ให้ถูกต้อง\x1b[0m')
        input("\nกด Enter เพื่อลองใหม่...")
        หน้าหลัก()
        return

    print('\n\x1b[33m[*] กำลังดึงรายละเอียดจากคลิป สักครู่พี่...\x1b[0m')
    ข้อมูล = ดึงข้อมูลคลิป(ลิงก์)

    if not ข้อมูล:
        print('\x1b[31m[!] ไม่สามารถดึงข้อมูลคลิปนี้ได้ หรือลิงก์ไม่ถูกต้อง\x1b[0m')
        input("\nกด Enter เพื่อกลับหน้าหลัก...")
        หน้าหลัก()
        return

    print(f"\n\x1b[92m=== รายละเอียดคลิป ===\x1b[0m")
    print(f"📌 ชื่อคลิป: {ข้อมูล['หัวข้อ']}")
    print(f"👤 ช่อง: {ข้อมูล['ช่อง']}")
    print(f"⏱️ ความยาว: {ข้อมูล['ความยาว']} วินาที")
    print(f"👁️ ยอดวิว: {ข้อมูล['ยอดวิว']} ครั้ง")
    print(f"======================\n")

    ถามเรื่องเปิดเสียง(ข้อมูล['ลิงก์เสียง'])

def ถามเรื่องเปิดเสียง(ลิงก์เสียง):
    คำตอบ = input("\x1b[35m[?] คุณต้องการจะเปิดเสียงนี้ไหม? (y/n): \x1b[0m").strip().lower()
    if คำตอบ == 'y':
        print('\x1b[32m[+] กำลังเปิดเสียงในเครื่องให้ทันที...\x1b[0m')
        เล่นเสียงคลิป(ลิงก์เสียง)
        input("\n\x1b[32m[✓] เล่นเสียงเสร็จสิ้น! กด Enter เพื่อกลับหน้าหลัก...\x1b[0m")
        หน้าหลัก()
    elif คำตอบ == 'n':
        print('\x1b[31m[-] ยกเลิกการเปิดเสียง\x1b[0m')
        input("\nกด Enter เพื่อกลับหน้าหลัก...")
        หน้าหลัก()
    else:
        print('\x1b[33m[!] ตอบแค่ y หรือ n เท่านั้นนะพี่\x1b[0m')
        ถามเรื่องเปิดเสียง(ลิงก์เสียง)
      
